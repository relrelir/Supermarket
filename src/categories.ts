export const CATEGORY_BY_ID: Record<string, Category> = Object.fromEntries(
  CATEGORIES.map((c) => [c.id, c]),
);

export function categoryOrder(id: string): number {
  const i = CATEGORIES.findIndex((c) => c.id === id);
  return i === -1 ? CATEGORIES.length : i;
}

/** Guesses a category from a Hebrew item name. Longest matching keyword wins. */
export function guessCategory(name: string): string {
  const text = name.trim();
  let best = { id: 'other', len: 0 };
  for (const cat of CATEGORIES) {
    for (const kw of cat.keywords) {
      if (kw.length > best.len && text.includes(kw)) best = { id: cat.id, len: kw.length };
    }
  }
  return best.id;
}
